export type AppIconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 20,
  color = 'currentColor',
  strokeWidth = 2.2,
  ...props
}: {
  name: string;
  size?: number;
  color?: string;
  strokeWidth?: number;
} & SVGProps<SVGSVGElement>) {
  const Cmp = ICONS[name as AppIconName] ?? Star;
  return <Cmp size={size} color={color} strokeWidth={strokeWidth} aria-hidden {...props} />;
}
